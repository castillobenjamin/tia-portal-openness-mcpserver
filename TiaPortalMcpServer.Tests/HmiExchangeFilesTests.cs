using System;
using System.IO;
using System.Linq;
using TiaPortalMcpServer.Services;
using Xunit;

namespace TiaPortalMcpServer.Tests
{
    [Trait("Category", "Unit")]
    public class HmiExchangeFilesTests
    {
        [Theory]
        [InlineData("GraphicLists", "GraphicLists")]
        [InlineData(" GraphicLists ", "GraphicLists")]
        [InlineData("GraphicLists.hmi.yml", "GraphicLists")]
        [InlineData("GraphicLists.HMI.YML", "GraphicLists")]
        [InlineData("GraphicLists.xlsx", "GraphicLists.xlsx")]
        [InlineData(".hmi.yml", ".hmi.yml")]
        public void ExportBaseName_DropsTrailingYamlExtension(string fileName, string expected)
        {
            Assert.Equal(expected, HmiExchangeFiles.ExportBaseName(fileName));
        }

        [Fact]
        public void FindImportFile_BaseName_FindsTheExportedYamlFile()
        {
            using (var files = new SimaticMlTestFiles())
            {
                var written = files.Write("GraphicLists.hmi.yml", "#Version: 2.0");

                var found = HmiExchangeFiles.FindImportFile(files.Root, "GraphicLists");

                Assert.Equal(written, found.FullName);
            }
        }

        [Fact]
        public void FindImportFile_FullName_IsUsedAsGiven()
        {
            using (var files = new SimaticMlTestFiles())
            {
                var written = files.Write("SystemTextLists.hmi.yml", "#Version: 2.0");
                files.Write("SystemTextLists.TextLibrary.hmi.yml", "#Version: 2.0");

                var found = HmiExchangeFiles.FindImportFile(files.Root, "SystemTextLists.hmi.yml");

                Assert.Equal(written, found.FullName);
            }
        }

        [Fact]
        public void FindTagTableDirectories_MapsDirectoriesToGroupsAndTables()
        {
            using (var files = new SimaticMlTestFiles())
            {
                files.Write("stray.txt", "x");
                files.Write(Path.Combine("Default tag table", "Tags.hmi.yml"), "x");
                files.Write(Path.Combine("Alarms", "Station", "HmiAlarmTags", "Tags.hmi.yml"), "x");
                Directory.CreateDirectory(Path.Combine(files.Root, "Empty"));

                var found = HmiExchangeFiles.FindTagTableDirectories(new DirectoryInfo(files.Root));

                Assert.Equal(2, found.Count);
                Assert.Equal("Alarms/Station", found[0].GroupPath);
                Assert.Equal("HmiAlarmTags", found[0].TableName);
                Assert.Equal("", found[1].GroupPath);
                Assert.Equal("Default tag table", found[1].TableName);
            }
        }

        [Fact]
        public void TagTableDirectory_RoundTripsThroughFindTagTableDirectories()
        {
            using (var files = new SimaticMlTestFiles())
            {
                var directory = HmiExchangeFiles.TagTableDirectory(files.Root, "Alarms/Station", "HmiAlarmTags");
                Directory.CreateDirectory(directory);
                File.WriteAllText(Path.Combine(directory, "Tags.hmi.yml"), "x");

                var found = Assert.Single(HmiExchangeFiles.FindTagTableDirectories(new DirectoryInfo(files.Root)));

                Assert.Equal(Path.Combine(files.Root, "Alarms", "Station", "HmiAlarmTags"), found.Directory.FullName);
                Assert.Equal("Alarms/Station", found.GroupPath);
                Assert.Equal("HmiAlarmTags", found.TableName);
            }
        }

        [Fact]
        public void FindImportFile_Missing_ReturnsNull()
        {
            using (var files = new SimaticMlTestFiles())
            {
                Assert.Null(HmiExchangeFiles.FindImportFile(files.Root, "GraphicLists"));
            }
        }

        [Fact]
        public void WrittenFile_CompletesAPathWithoutTheYamlExtension()
        {
            using (var files = new SimaticMlTestFiles())
            {
                var written = files.Write(Path.Combine("Alarms", "HmiAlarmTags", "HmiAlarmTags.hmi.yml"), "x");
                var reported = Path.Combine(files.Root, "Alarms", "HmiAlarmTags", "HmiAlarmTags");

                Assert.Equal(written, HmiExchangeFiles.WrittenFile(new FileInfo(reported)));
                Assert.Equal(written, HmiExchangeFiles.WrittenFile(new FileInfo(written)));
                Assert.Equal(reported + ".txt", HmiExchangeFiles.WrittenFile(new FileInfo(reported + ".txt")));
            }
        }

        private const string MarkerComment =
            "/*<auto-generated>\r\n" +
            "***End of Global definition area***\r\n" +
            "Changes to this comment may cause incorrect behavior during document based import.\r\n" +
            "</auto-generated>*/\r\n";

        private static string[] Lines(string text)
        {
            return text.Split(new[] { "\r\n" }, StringSplitOptions.None);
        }

        [Fact]
        public void CommentLinesAfterGlobalArea_CountsCommentsBeforeTheFirstFunction()
        {
            var text = "\r\n" + MarkerComment +
                "// ====\r\n// AisleOperations\r\n\r\n/* block\r\n   comment */\r\n" +
                "export function RequestChgTerminal(station, n) {\r\n  // inside\r\n}\r\n";

            Assert.Equal(4, HmiExchangeFiles.CommentLinesAfterGlobalArea(Lines(text)));
        }

        [Theory]
        [InlineData("export function HideMainNavigation() {\r\n}\r\n")]
        [InlineData("\r\nexport function A() {\r\n}\r\n// trailing\r\n")]
        public void CommentLinesAfterGlobalArea_FunctionRightAfterTheMarker_IsZero(string body)
        {
            Assert.Equal(0, HmiExchangeFiles.CommentLinesAfterGlobalArea(Lines("\r\n" + MarkerComment + body)));
        }

        [Fact]
        public void CommentLinesAfterGlobalArea_NoMarker_IsZero()
        {
            Assert.Equal(0, HmiExchangeFiles.CommentLinesAfterGlobalArea(Lines("// header\r\nexport function A() {}\r\n")));
        }

        [Fact]
        public void GlobalAreaWarnings_NameOnlyTheAffectedScriptFiles()
        {
            using (var files = new SimaticMlTestFiles())
            {
                var yml = files.Write("AisleOperations.hmi.yml", "ScriptModules:\n");
                files.Write("AisleOperations.hmi.js", "\r\n" + MarkerComment + "// header\r\nexport function A() {}\r\n");
                var navigation = files.Write("Navigation.hmi.js", "\r\n" + MarkerComment + "export function B() {}\r\n");

                var scripts = HmiExchangeFiles.ScriptFiles(new[] { yml, navigation, Path.Combine(files.Root, "AisleOperations.hmi.js") });
                var warnings = HmiExchangeFiles.GlobalAreaWarnings(scripts);

                Assert.Equal(new[] { "AisleOperations.hmi.js", "Navigation.hmi.js" }, scripts.Select(f => f.Name).ToArray());
                Assert.Equal(2, warnings.Count);
                Assert.StartsWith("1 script file(s)", warnings[0]);
                Assert.Equal("AisleOperations.hmi.js: 1 comment line(s) after the end of the global definition area, before the first function", warnings[1]);
            }
        }

        [Fact]
        public void SystemTextListFiles_IncludesTheTextLibraryFile()
        {
            using (var files = new SimaticMlTestFiles())
            {
                var main = files.Write("SystemTextLists.hmi.yml", "x");
                var library = files.Write("SystemTextLists.TextLibrary.hmi.yml", "y");

                var found = HmiExchangeFiles.SystemTextListFiles(new FileInfo(main));

                Assert.Equal(new[] { main, library }, found.Select(f => f.FullName).ToArray());
            }
        }

        [Fact]
        public void SystemTextListFiles_WithoutTextLibrary_ReturnsTheMainFileOnly()
        {
            using (var files = new SimaticMlTestFiles())
            {
                var main = files.Write("SystemTextLists.hmi.yml", "x");

                var found = Assert.Single(HmiExchangeFiles.SystemTextListFiles(new FileInfo(main)));

                Assert.Equal(main, found.FullName);
            }
        }

        [Fact]
        public void DoubleEscapeWarnings_ListsOnlyLinesWithDoubleAt()
        {
            using (var files = new SimaticMlTestFiles())
            {
                var main = files.Write("SystemTextLists.hmi.yml", "Text: MyTextLibrary.Text_1\n");
                files.Write("SystemTextLists.TextLibrary.hmi.yml",
                    "      Text_117:\n" +
                    "        - Unknown error (@3%s@)\n" +
                    "        - 'scheduled for: @@5%Y-%m-%d %H:%M:%S@@.'\n");

                var warnings = HmiExchangeFiles.DoubleEscapeWarnings(HmiExchangeFiles.SystemTextListFiles(new FileInfo(main)));

                Assert.Equal(2, warnings.Count);
                Assert.StartsWith("1 line(s) hold '@@'", warnings[0]);
                Assert.Equal("SystemTextLists.TextLibrary.hmi.yml line 3: - 'scheduled for: @@5%Y-%m-%d %H:%M:%S@@.'", warnings[1]);
            }
        }

        [Fact]
        public void DoubleEscapeWarnings_NoDoubleAt_ReturnsNothing()
        {
            using (var files = new SimaticMlTestFiles())
            {
                var main = files.Write("SystemTextLists.hmi.yml", "- Unknown error (@3%s@)\n");

                Assert.Empty(HmiExchangeFiles.DoubleEscapeWarnings(new[] { new FileInfo(main) }));
            }
        }

        [Fact]
        public void DoubleEscapeWarnings_ManyLines_ListsTheFirstAndCountsTheRest()
        {
            using (var files = new SimaticMlTestFiles())
            {
                var lines = string.Concat(Enumerable.Range(1, HmiExchangeFiles.MaxListedDoubleEscapes + 5).Select(i => $"- '@@{i}@@'\n"));
                var main = files.Write("SystemTextLists.hmi.yml", lines);

                var warnings = HmiExchangeFiles.DoubleEscapeWarnings(new[] { new FileInfo(main) });

                Assert.Equal(HmiExchangeFiles.MaxListedDoubleEscapes + 2, warnings.Count);
                Assert.StartsWith($"{HmiExchangeFiles.MaxListedDoubleEscapes + 5} line(s)", warnings[0]);
                Assert.Equal("... and 5 more line(s) holding '@@'", warnings[warnings.Count - 1]);
            }
        }
    }
}
